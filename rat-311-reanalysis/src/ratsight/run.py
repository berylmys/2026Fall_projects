"""Run the experiments from the command line.

    python -m ratsight.run --config config.yaml
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

from ratsight import metrics
from ratsight.experiments import Context, Result, run_experiment
from ratsight.load import load_population, load_sightings, same_records


def load_config(path: str | Path) -> dict[str, Any]:
    """Read a YAML config and resolve data paths relative to the config file."""
    path = Path(path)
    cfg = yaml.safe_load(path.read_text())
    base = path.parent
    for key in ("sightings_csv", "population_csv", "duplicate_check_csv"):
        if cfg.get("data", {}).get(key):
            cfg["data"][key] = str((base / cfg["data"][key]).resolve())
    cfg["output_dir"] = str((base / cfg.get("output_dir", "outputs")).resolve())
    return cfg


def write_result(result: Result, out_dir: Path) -> None:
    """Write an experiment's tables as CSV files under ``out_dir/tables``."""
    table_dir = out_dir / "tables"
    table_dir.mkdir(parents=True, exist_ok=True)
    for name, table in result.tables.items():
        table.to_csv(table_dir / f"{name}.csv")


def summary_markdown(results: list[Result], notes: list[str]) -> str:
    """Put the results into a Markdown summary."""
    lines = ["# Results summary", "", "Generated by `python -m ratsight.run`.", ""]
    lines += [f"- {n}" for n in notes] + [""]
    for r in results:
        lines += [f"## {r.key}: {r.hypothesis}", "", r.verdict, ""]
        for fig in r.figures:
            lines.append(f"![{r.key}](figures/{fig.name})")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> list[Result]:
    """Run the experiments, save the outputs, and return the results."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config.yaml")
    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    out_dir = Path(cfg["output_dir"])
    data = cfg["data"]

    sightings = load_sightings(data["sightings_csv"])
    years_cfg = cfg.get("years", "complete")
    years = metrics.complete_years(sightings) if years_cfg == "complete" else list(years_cfg)
    ctx = Context(sightings, load_population(data["population_csv"]), years, out_dir,
                  seed=cfg.get("seed", 0), n_boot=cfg.get("n_boot", 1000))

    notes = [f"Records loaded: {len(sightings):,}",
             f"Date range: {sightings['Created Date'].min():%Y-%m-%d} to "
             f"{sightings['Created Date'].max():%Y-%m-%d}",
             f"Complete years analysed: {years[0]}-{years[-1]}"]
    if data.get("duplicate_check_csv") and Path(data["duplicate_check_csv"]).exists():
        same = same_records(data["sightings_csv"], data["duplicate_check_csv"])
        notes.append(f"'Rats Heat Map' export has identical records to 'Rat Sightings': {same}")

    results = []
    for name, params in cfg["experiments"].items():
        result = run_experiment(name, ctx, params)
        write_result(result, out_dir)
        print(f"[{result.key}] {result.verdict}")
        results.append(result)
    (out_dir / "summary.md").write_text(summary_markdown(results, notes))
    return results


if __name__ == "__main__":
    main()
